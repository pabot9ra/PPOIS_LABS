#ifndef INSTRUCTION_H
#define INSTRUCTION_H

#include <iosfwd>

/// @brief Тип команды машины Поста
enum class OpType {
    Mark,     ///< V - поставить метку в ячейку под кареткой
    Erase,    ///< X - стереть метку в ячейке под кареткой
    Right,    ///< -> - сдвинуть каретку на одну ячейку вправо
    Left,     ///< <- - сдвинуть каретку на одну ячейку влево
    Branch,   ///< ? - ветвление по наличию метки под кареткой
    Stop      ///< ! - остановить машину
};

/// @brief Одна команда программы машины Поста
/// @details Команда только хранит свой тип и номера переходов, сама ничего не выполняет - выполнение в PostMachine::step().
/// Номера команд нумеруются с единицы. next2 используется только у ветвления, у остальных команд равен 0
class Instruction {
private:
    OpType type_;
    int next1_;
    int next2_;

public:
    /// @brief создание команды по умолчанию - остановка (!)
    /// @details выбран Stop как безопасное значение: незаполненная команда при выполнении просто остановит машину и не изменит ленту
    Instruction();

    /// @brief создание команды с одним переходом: V, X, -> или <-
    /// @param type тип команды
    /// @param next1 номер команды, которая выполнится следующей
    Instruction(OpType type, int next1);

    /// @brief создание команды с двумя переходами - ветвления (?)
    /// @param type тип команды
    /// @param next1 номер следующей команды, если под кареткой метка
    /// @param next2 номер следующей команды, если ячейка пустая
    Instruction(OpType type, int next1, int next2);

    /// @brief возвращает тип команды
    /// @return тип команды
    OpType type() const;

    /// @brief возвращает первый номер перехода
    /// @return номер следующей команды; у ветвления - переход при наличии метки
    int next1() const;

    /// @brief возвращает второй номер перехода
    /// @return у ветвления - переход при пустой ячейке, у остальных команд 0
    int next2() const;

    /// @brief позволяет проверить на равность две команды
    /// @details команды равны, если совпадают тип и оба номера перехода
    /// @param other команда для сравнения
    /// @return true если команды равны, false когда неравны
    bool operator==(const Instruction &other) const;

    /// @brief позволяет проверить на неравность две команды
    /// @param other команда для сравнения
    /// @return true если команды неравны, false когда равны
    bool operator!=(const Instruction &other) const;
};

/// @brief позволяет выводить команду в поток
/// @details формат: V 3, X 3, -> 3, <- 3, ? 3, 1, !
/// @param os поток вывода
/// @param ins команда
/// @return возвращает поток вывода
std::ostream& operator<<(std::ostream &os, const Instruction &ins);

/// @brief позволяет читать команду из потока
/// @details формат тот же, что при выводе. При неизвестной команде поток переводится в состояние ошибки
/// @param is поток ввода
/// @param ins команда, в которую записывается результат
/// @return возвращает поток ввода
std::istream& operator>>(std::istream &is, Instruction &ins);

#endif