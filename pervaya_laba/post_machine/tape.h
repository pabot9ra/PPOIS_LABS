#ifndef TAPE_H
#define TAPE_H

#include <set>
#include <iosfwd>

/// @brief Класс реализует бесконечную ленту
/// @details Лента хранит множество помеченных ячеек, лента бесконечна в обе стороны, позиции могут быть отрицательными, все что не в множестве считается пустым
class Tape {
private:
    std::set<long long> marked_;

public:
    /// @brief создание пустой ленты(0 помеченных ячеек)
    Tape();
    /// @brief Возвращает состояние ячейки: помечена или нет
    /// @param pos позиция ячейки на ленте 
    /// @return возвращает true в случае наличия метки, false если ее нет
    bool isMarked(long long pos) const;

    /// @brief помечает ячейку ленты(добавляет в множество помеченных)
    /// @details на уже помеченной ячейке ошибкой не считается
    /// @param pos позиция ячейки на ленте
    void mark(long long pos);

    /// @brief удаляет метку с ячейки ленты(удаляет из множества помеченных)
    /// @details на пустой ячейке ошибкой не считается
    /// @param pos позиция ячейки на ленте
    void unmark(long long pos);

    /// @brief очищает ленту убирая все метки(очищает множество помеченных)
    void clear();

    /// @brief проверяет что нет помеченных ячеек ленты
    /// @return true если на ленте ни одной метки
    bool empty() const;

    /// @brief считает количество помеченных ячеек ленты
    /// @return возвращает число помеченных ячеек ленты
    long long count() const;

    /// @brief находит наименьшую позицию среди всех помеченных ячеек ленты
    /// @return возвращает наименьшую позицию помеченной ячейки ленты
    /// @details на пустой ленте вернет 0
    long long minPos() const;

    /// @brief находит наибольшую позицию среди всех помеченных ячеек ленты
    /// @return возвращает наибольшую позицию помеченной ячейки ленты
    /// @details на пустой ленте вернет 0
    long long maxPos() const;

    /// @brief позволяет проверить на равность две ленты
    /// @param other лента для сравнения 
    /// @return true если ленты равны, false когда неравны
    bool operator==(const Tape &other) const;

    /// @brief позволяет проверить на неравность две ленты
    /// @param other лента для сравнения 
    /// @return true если ленты неравны, false когда равны
    bool operator!=(const Tape &other) const;
};

/// @brief позволяет выводить ленту в поток
/// @details формат: [номер первой помеченной ячейки] V . V; для пустой ленты: (empty tape)
/// @param os поток вывода
/// @param tape лента
/// @return возвращает поток вывода
std::ostream& operator<<(std::ostream &os, const Tape &tape);

/// @brief позволяет читать ленту из потока
/// @details если чтение не удалось вернет поток в состоянии ошибки,
/// формат: позиция первого символа V.V; содержимое ленты полностью заменяется, а не дописывается
/// @param is поток ввода
/// @param tape лента
/// @return возвращает поток ввода
std::istream& operator>>(std::istream &is, Tape &tape);

#endif