/// @author Владислав Вертинский
/// @brief Машина Поста

#ifndef POSTMACHINE_H
#define POSTMACHINE_H
#include "tape.h"
#include "program.h"
#include <iosfwd>

/// @brief Состояние машины Поста
enum class State{
    Running,  ///< машина работает, можно делать шаги
    Stopped,  ///< машина остановилась на команде ! - нормальное завершение
    Error     ///< машина остановилась с ошибкой: V на помеченной ячейке, X на пустой или переход на несуществующую команду
};

/// @brief Машина Поста: лента, программа, каретка и номер текущей команды
/// @details Машина выполняет программу по одной команде за шаг и проверяет правила машины Поста - лента и программа сами ничего не проверяют.
/// После остановки (Stopped или Error) шаги не выполняются, пока не вызван reset()
class PostMachine{
private:
   Tape tape_;
   Program program_;
   long long pos_;
   int current_;
   State state_;



public:
    /// @brief создание машины с пустой лентой и пустой программой
    /// @details каретка в позиции 0, текущая команда 1, состояние Running
    PostMachine();

    /// @brief создание машины с заданной лентой, программой и позицией каретки
    /// @details текущая команда 1, состояние Running
    /// @param tape начальная лента
    /// @param prog программа
    /// @param pos начальная позиция каретки
    PostMachine(const Tape &tape, const Program &prog, long long pos);

    /// @brief возвращает ленту
    /// @return ссылка на ленту, изменить через неё нельзя - только через setTape()
    const Tape& tape() const;

    /// @brief возвращает программу
    /// @return ссылка на программу, изменить через неё нельзя - только через setProgram()
    const Program& program() const;

    /// @brief возвращает позицию каретки
    /// @return номер ячейки под кареткой
    long long position() const;

    /// @brief возвращает номер текущей команды
    /// @details после остановки на ! остаётся номер этой команды, после ошибки - номер команды, на которой она произошла
    /// @return номер команды, которая выполнится следующим шагом
    int current() const;

    /// @brief возвращает состояние машины
    /// @return Running, Stopped или Error
    State state() const;

    /// @brief заменяет ленту
    /// @details состояние и номер текущей команды не меняются - для повторного запуска нужен reset()
    /// @param tape новая лента
    void setTape(const Tape &tape);

    /// @brief заменяет программу
    /// @details состояние и номер текущей команды не меняются - для повторного запуска нужен reset()
    /// @param program новая программа
    void setProgram(const Program &program);

    /// @brief ставит каретку в заданную позицию
    /// @param pos новая позиция каретки
    void setPosition(long long pos);

    /// @brief подготавливает машину к запуску программы с начала
    /// @details текущая команда 1, состояние Running. Лента и каретка не меняются - это позволяет запускать программу на результате предыдущего запуска
    void reset();

    /// @brief выполняет одну команду
    /// @details при V на помеченной ячейке и X на пустой лента не меняется, номер команды остаётся прежним, состояние становится Error.
    /// Переход на несуществующую команду обнаруживается на следующем шаге, а не при самом переходе
    /// @return true если команда выполнена (включая !), false если машина уже остановлена или произошла ошибка
    bool step();

    /// @brief выполняет шаги, пока машина работает, но не больше limit
    /// @details лимит защищает от бесконечного цикла в программе. Если лимит исчерпан, машина остаётся в состоянии Running
    /// @param limit максимальное число шагов
    /// @return число выполненных шагов, включая шаг с командой !; шаг с ошибкой не считается
    int run(int limit);

    /// @brief префиксный инкремент - выполняет один шаг
    /// @return ссылка на эту же машину после шага
    PostMachine& operator++();

    /// @brief постфиксный инкремент - выполняет один шаг
    /// @return копия машины до шага
    PostMachine operator++(int);

    /// @brief позволяет проверить на равность две машины
    /// @details машины равны, если совпадают лента, программа, позиция каретки, номер текущей команды и состояние
    /// @param other машина для сравнения
    /// @return true если машины равны, false когда неравны
    bool operator==(const PostMachine &other) const;

    /// @brief позволяет проверить на неравность две машины
    /// @param other машина для сравнения
    /// @return true если машины неравны, false когда равны
    bool operator!=(const PostMachine &other) const;

};

/// @brief позволяет выводить машину в поток
/// @details формат: состояние в квадратных скобках, текущая команда с номером, позиция каретки, лента.
/// Формат вывода отличается от формата файла - прочитать выведенную машину обратно через >> нельзя
/// @param os поток вывода
/// @param machine машина
/// @return возвращает поток вывода
std::ostream& operator<<(std::ostream &os, const PostMachine &machine);

/// @brief позволяет читать машину из потока
/// @details формат: строка tape: с лентой, строка carriage: с позицией каретки, затем команды программы до конца потока.
/// При ошибке поток переводится в состояние ошибки, а машина не меняется. При успехе вызывается reset()
/// @param is поток ввода
/// @param machine машина, в которую записывается результат
/// @return возвращает поток ввода
std::istream& operator>>(std::istream &is, PostMachine &machine);


#endif