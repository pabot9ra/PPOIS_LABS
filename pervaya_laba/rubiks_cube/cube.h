#ifndef CUBE_H
#define CUBE_H
#include <array>
#include "face.h"
#include <iosfwd>


/// @brief Положение грани на кубике
/// @details значение используется как номер грани в массиве граней кубика, поэтому порядок важен:
/// от него зависят конструктор Cube и нумерация граней в меню
enum class FaceId{
    U,  ///< верхняя
    L,  ///< левая
    F,  ///< передняя
    R,  ///< правая
    B,  ///< задняя
    D   ///< нижняя
};

/// @brief Направление хода
/// @details направление считается, если смотреть прямо на поворачиваемую грань. Порядок значений совпадает с нумерацией в меню
enum class Turn{
    Clockwise,         ///< по часовой стрелке
    CounterClockwise,  ///< против часовой стрелки
    DoubleMove         ///< на 180 градусов
};

/// @brief Кубик Рубика 3 на 3 - шесть граней по 9 наклеек
/// @details снаружи кубик меняется только ходами через move() и чтением из потока, поэтому в нём не может появиться
/// невозможное состояние из-за прямой подмены наклеек. Грани для просмотра выдаются только для чтения через face()
class Cube{
    private:
        std::array<Face, 6> faces_;
        void moveU();
        void moveR();
        void moveL();
        void moveD();
        void moveF();
        void moveB();
    public:
        /// @brief создание собранного кубика
        /// @details стандартная раскраска: U белая, L оранжевая, F зелёная, R красная, B синяя, D жёлтая
        Cube();

        /// @brief возвращает грань для просмотра
        /// @details изменить грань через эту ссылку нельзя - кубик меняется только ходами
        /// @param id положение грани
        /// @return ссылка на грань
        const Face& face(FaceId id) const;

        /// @brief проверяет, собран ли кубик
        /// @return true если каждая из шести граней одноцветная
        bool isSolved() const;
        
        /// @brief делает ход
        /// @details поворачивается сама грань и переносятся 12 наклеек соседних граней; противоположная грань не меняется.
        /// Против часовой выполняется как три поворота по часовой, двойной - как два
        /// @param face какую грань повернуть
        /// @param turn направление хода
        void move(FaceId face, Turn turn);

        /// @brief перемешивает кубик случайными ходами
        /// @details каждый ход - случайная грань и случайное направление. Кубик перемешивается ходами, а не случайной
        /// расстановкой цветов, поэтому его всегда можно собрать. При каждом вызове генератор получает новое начальное число
        /// @param count количество случайных ходов
        void mix(int count);

        /// @brief позволяет читать кубик из потока
        /// @details объявлен другом класса, потому что записывает грани напрямую, а публичного способа подменить грань нет
        friend std::istream& operator>>(std::istream &is, Cube &cube);

        /// @brief позволяет проверить на равность два кубика
        /// @details кубики равны, если совпадают все шесть граней
        /// @param other кубик для сравнения
        /// @return true если кубики равны, false когда неравны
        bool operator==(const Cube &other) const;

        /// @brief позволяет проверить на неравность два кубика
        /// @param other кубик для сравнения
        /// @return true если кубики неравны, false когда равны
        bool operator!=(const Cube &other) const;
};

/// @brief позволяет выводить кубик в поток
/// @details выводится развёртка буквами: сверху грань U с отступом, затем три строки граней L F R B подряд, внизу грань D с отступом
/// @param os поток вывода
/// @param cube кубик
/// @return возвращает поток вывода
std::ostream& operator<<(std::ostream &os, const Cube &cube);

/// @brief позволяет читать кубик из потока
/// @details формат тот же, что при выводе: 54 буквы в порядке U, затем ряды L F R B, затем D; пробелы и переводы строк не важны.
/// Проверяется, что каждого цвета ровно 9 и все центры разные. Полная проверка того, что кубик можно собрать, не делается.
/// При любой ошибке поток переводится в состояние ошибки, а cube не меняется
/// @param is поток ввода
/// @param cube кубик, в который записывается результат
/// @return возвращает поток ввода
std::istream& operator>>(std::istream &is, Cube &cube);

#endif
