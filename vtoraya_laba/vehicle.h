/// @brief Транспорт с маршрутом и копиями загруженных мешков.

#ifndef VEHICLE_H
#define VEHICLE_H

#include "mailbag.h"
#include "route.h"
#include <cstddef>
#include <string>
#include <vector>

/// @brief Транспорт с маршрутом и копиями загруженных мешков.
/// @details Прибытие возможно только на следующую остановку; выгрузка — по адресу мешка. Статусы отправлений в отделении не меняются.
class Vehicle {
private:
    std::string plate_; ///< Регистрационный номер транспорта.
    int maximumLoad_; ///< Грузоподъёмность, г.
    Route route_; ///< Копия плана маршрута.
    std::vector<MailBag> bags_; ///< Мешки центра или транспорта.
    std::size_t currentStop_; ///< Индекс последней достигнутой остановки.
    bool moving_; ///< Движется ли транспорт.

    /// @brief Проверяет остановку, пломбу, маршрут и грузоподъёмность перед загрузкой.
    /// @param bag Почтовый мешок; при загрузке сохраняется копией.
    void ensureCanLoad(const MailBag &bag) const;
    /// @brief Проверяет отсутствие повторного мешка и повторных вложений в транспорте.
    /// @param bag Почтовый мешок; при загрузке сохраняется копией.
    void ensureUniqueContents(const MailBag &bag) const;

public:
    /// @brief Создаёт стоящий транспорт на первой остановке готового маршрута.
    /// @param plate Непустой регистрационный номер транспорта.
    /// @param maximumLoad Положительная грузоподъёмность транспорта в граммах.
    /// @param route Маршрут как минимум с двумя остановками.
    Vehicle(const std::string &plate, int maximumLoad, const Route &route);

    /// @brief Регистрационный номер транспорта.
    /// @return Регистрационный номер транспорта.
    const std::string &plate() const;
    /// @brief Грузоподъёмность транспорта в граммах.
    /// @return Грузоподъёмность транспорта в граммах.
    int maximumLoad() const;
    /// @brief Последнее достигнутое отделение; в пути сохраняется до прибытия.
    /// @return Последнее достигнутое отделение; в пути сохраняется до прибытия.
    /// @note Во время движения возвращается последнее достигнутое отделение, а не будущая остановка.
    int currentBranchId() const;
    /// @brief Признак движения транспорта.
    /// @return Признак движения транспорта.
    bool moving() const;
    /// @brief Число учитываемых мешков.
    /// @return Число учитываемых мешков.
    std::size_t bagCount() const;
    /// @brief Суммирует вес загруженных мешков в граммах.
    /// @return Суммарный вес загруженных вложений в граммах.
    int loadGrams() const;
    /// @brief Вычисляет оставшуюся грузоподъёмность в граммах.
    /// @return Допустимый вес дополнительных вложений в граммах.
    int remainingCapacity() const;
    /// @brief Загружает копию запечатанного мешка с проверкой маршрута, веса и повторов вложений.
    /// @param bag Почтовый мешок; при загрузке сохраняется копией.
    /// @throws CapacityExceededException Недостаточна оставшаяся грузоподъёмность.
    /// @throws std::logic_error Транспорт движется или мешок открыт.
    /// @throws std::invalid_argument Неверен маршрут или повторяется мешок либо вложение.
    void loadBag(const MailBag &bag);
    /// @brief Выдаёт и удаляет мешок только на его остановке назначения.
    /// @param bagId Идентификатор мешка.
    /// @return Самостоятельная копия выгруженного мешка.
    MailBag unloadBag(const std::string &bagId);
    /// @brief Начинает движение к следующей остановке после выгрузки местных мешков.
    void depart();
    /// @brief Завершает движение только на следующей остановке маршрута.
    /// @param branchId Идентификатор отделения.
    void arriveAt(int branchId);
};

#endif
